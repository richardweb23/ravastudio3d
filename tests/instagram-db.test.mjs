import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import assert from 'node:assert/strict';

test('base Instagram impede ativação e protege dados para perfis inativos e anônimos', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated;
    create table public.materiais(id uuid primary key, nome text);
    create table public.catalogo_categorias(id uuid primary key, ativa boolean);
    create table public.catalogo_produtos(material_id uuid primary key references public.materiais(id), titulo text, slug text, preco_centavos bigint, promocional_centavos bigint, categoria_id uuid references public.catalogo_categorias(id), status text);
    create function public.usuario_ativo() returns boolean language sql stable as $$
      select current_setting('test.ativo', true) = 'sim'
    $$;
    grant usage on schema public to authenticated, anon;`);
  await db.exec(readFileSync('supabase/instagram-draft/202611070001_instagram_base.sql', 'utf8'));
  await db.exec("insert into public.materiais values('10000000-0000-4000-8000-000000000001','Peça'); insert into public.catalogo_produtos values('10000000-0000-4000-8000-000000000001','','peca',5000,4000,null,'publicado'); insert into public.instagram_publicacoes(id) values('post'); insert into public.instagram_publicacao_produtos values('post','10000000-0000-4000-8000-000000000001');");
  await db.exec("update public.instagram_publicacoes set monitorada=true where id='post'; select public.instagram_sincronizar_publicacoes('[{\"id\":\"post\",\"caption\":\"Atualizada\"}]'::jsonb)");
  assert.equal((await db.query("select monitorada from public.instagram_publicacoes where id='post'")).rows[0].monitorada, true);
  assert.equal((await db.query("select * from public.instagram_publicacao_produtos where publicacao_id='post'")).rows.length, 1);
  assert.equal((await db.query("select public.instagram_contexto('post') as ctx")).rows[0].ctx.configuracao.ativa, false);
  const products = await db.query("select * from public.instagram_produtos_publicos('post')");
  assert.equal(products.rows[0].nome, 'Peça'); assert.equal(Number(products.rows[0].promocional_centavos), 4000);
  await db.exec('update public.catalogo_produtos set promocional_centavos=3500');
  assert.equal(Number((await db.query("select * from public.instagram_produtos_publicos('post')")).rows[0].promocional_centavos), 3500);
  await db.exec("insert into public.catalogo_categorias values('20000000-0000-4000-8000-000000000001',false); update public.catalogo_produtos set categoria_id='20000000-0000-4000-8000-000000000001'");
  assert.equal((await db.query("select * from public.instagram_produtos_publicos('post')")).rows.length, 0);
  await db.exec('update public.catalogo_categorias set ativa=true');
  assert.equal((await db.query("select * from public.instagram_produtos_publicos('post')")).rows.length, 1);
  await db.exec("update public.catalogo_produtos set status='inativo'");
  assert.equal((await db.query("select * from public.instagram_produtos_publicos('post')")).rows.length, 0);
  assert.equal((await db.query('select ativa from public.instagram_configuracao')).rows[0].ativa, false);
  assert.equal((await db.query("select public.instagram_reservar_comentario('comment-a','post-a','valor') ok")).rows[0].ok, true);
  assert.equal((await db.query("select public.instagram_reservar_comentario('comment-a','post-a','valor') ok")).rows[0].ok, false);
  await db.exec("select public.instagram_registrar_estado('comment-a','envio_privado_iniciado')");
  assert.equal((await db.query("select status from public.instagram_atividade where comentario_id='comment-a'")).rows[0].status, 'envio_privado_iniciado');
  await assert.rejects(db.exec("select public.instagram_registrar_estado('comment-a','invalido')"), /inválido/i);
  const digest = 'a'.repeat(64);
  await db.query("insert into public.instagram_eventos_brutos(digest,payload) values($1,'{}')", [digest]);
  await assert.rejects(db.query("insert into public.instagram_eventos_brutos(digest,payload) values($1,'{}')", [digest]), /duplicate/i);
  const first = (await db.query('select * from public.instagram_reservar_evento()')).rows[0];
  assert.equal(first.estado, 'processando');
  assert.equal((await db.query('select * from public.instagram_reservar_evento()')).rows.length, 0);
  await db.exec("insert into public.instagram_comentarios_recebidos(comentario_id) values('comment-1'); insert into public.instagram_atividade(comentario_id,created_at) values('comment-1',now()-interval '91 days');");
  await db.query("update public.instagram_eventos_brutos set recebido_em=now()-interval '91 days' where digest=$1", [digest]);
  await db.exec('select public.instagram_limpar_registros()');
  assert.equal((await db.query('select * from public.instagram_atividade')).rows.length, 1);
  assert.equal((await db.query('select * from public.instagram_eventos_brutos')).rows.length, 1);
  assert.equal((await db.query('select * from public.instagram_comentarios_recebidos')).rows.length, 2);
  await db.query("update public.instagram_eventos_brutos set bloqueado_ate=now()-interval '1 minute' where digest=$1", [digest]);
  const second = (await db.query('select * from public.instagram_reservar_evento()')).rows[0];
  assert.notEqual(first.tentativa_id, second.tentativa_id);
  assert.equal((await db.query("select public.instagram_concluir_evento($1,$2,'concluido') ok", [digest, first.tentativa_id])).rows[0].ok, false);
  assert.equal((await db.query("select public.instagram_concluir_evento($1,$2,'concluido') ok", [digest, second.tentativa_id])).rows[0].ok, true);
  await db.exec('select public.instagram_limpar_registros()');
  assert.equal((await db.query('select * from public.instagram_eventos_brutos')).rows.length, 0);
  assert.equal((await db.query('select * from public.instagram_reservar_evento()')).rows.length, 0);
  await db.exec("select set_config('test.ativo','sim',false); set role authenticated");
  assert.equal((await db.query('select * from public.instagram_configuracao')).rows.length, 1);
  await db.exec("update public.instagram_configuracao set resposta_publica='Resposta de teste'");
  await assert.rejects(db.exec("update public.instagram_configuracao set mensagem_produto='Sem variável'"), /check constraint/i);
  await assert.rejects(db.exec("update public.instagram_configuracao set sem_produto='catalogo'"), /check constraint/i);
  await assert.rejects(db.exec("insert into public.instagram_publicacao_produtos values('post','10000000-0000-4000-8000-000000000001')"), /duplicate/i);
  await db.exec('update public.instagram_configuracao set ativa=true');
  assert.equal((await db.query('select ativa from public.instagram_configuracao')).rows[0].ativa, true);
  await assert.rejects(db.exec('select * from public.instagram_comentarios_recebidos'), /permission denied/i);
  await assert.rejects(db.exec('select * from public.instagram_reservar_evento()'), /permission denied/i);
  await db.exec("select set_config('test.ativo','nao',false)");
  assert.equal((await db.query('select * from public.instagram_configuracao')).rows.length, 0);
  assert.equal((await db.query("update public.instagram_configuracao set resposta_publica='Teste' returning id")).rows.length, 0);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.exec('select * from public.instagram_configuracao'), /permission denied/i);
});
